#!/usr/bin/env python3
"""Package only after the actual host and all five native result files pass."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
from zipfile import ZipFile, ZIP_DEFLATED

output = Path('dist')
host = json.loads((output / 'flutter-results.json').read_text())
if not host.get('success') or host['failed'] or host['skipped'] or host['passed'] < 1:
    raise SystemExit('Cannot package a failing or incomplete host run')
native = []
for name, expected in [('native-kdf', 10), ('native-pdf', 1), ('application', 1),
                       ('restart-setup', 1), ('restart-restore', 1)]:
    result = json.loads((output / 'native-results' / (name + '.json')).read_text())
    if result['target'] != name or result['passed'] != expected or result['failed'] or result['skipped']:
        raise SystemExit('Cannot package incomplete native acceptance: ' + name)
    native.append(result)
commit = os.environ['GITHUB_SHA']
run = os.environ['GITHUB_RUN_ID']
if not re.fullmatch('[a-f0-9]{40}', commit) or not run.isdigit():
    raise SystemExit('Invalid CI identity')
proof = dict(commit=commit, run_url='https://github.com/shehab5552/siraj-codex/actions/runs/' + run,
             host=host, native=native, physical_device=False,
             release_readiness='Integration Testing',
             gates={'code_quality': 'PASS', 'visual_fidelity': 'FAIL', 'physical_device': 'BLOCKED',
                    'production_ai_rag_quiz': 'BLOCKED', 'production_signing_and_auth_profile': 'BLOCKED'})
proof_json = json.dumps(proof, ensure_ascii=False, indent=2) + '\n'
md = ('# سجل قبول CI الفعلي\n\n'
      f'Commit: `{commit}`\n\n[CI]({proof["run_url"]})\n\n'
      f'Flutter: {host["passed"]} ناجحًا،0 فاشل،0 متخطى.\n\n'
      f'Android: {sum(r["passed"] for r in native)} ناجحًا،0 فاشل،0 متخطى؛ محاكي API33 فقط.\n\n'
      'تشمل النتائج KDF وPDF الأصلي والتطبيق وإعداد حالة محفوظة ثم استعادتها بعد adb force-stop. '
      'جُمعت الصور والعدادات على المضيف؛ لم تُنسخ SQLite أو Keystore لإعادة الحالة.\n\n'
      '**Integration Testing؛ لا اعتماد جهاز فعلي أو G2/G3 أو إنتاج.** '
      'المطابقة البصرية النهائية والموارد العلمية والتوقيع وملف Auth لها بوابات باقية في تقارير المشروع.\n')
(output / 'CI_ACCEPTANCE.json').write_text(proof_json)
(output / 'CI_ACCEPTANCE_AR.md').write_text(md)
archive = output / 'SIRAJ_P0_FINAL_FLUTTER_SOURCE.zip'
subprocess.run(['git', 'archive', '--format=zip', '--prefix=SIRAJ_P0/', commit, '-o', str(archive)], check=True)
# Evidence is generated by this CI, not represented as a tracked source file.
with ZipFile(archive, 'a', compression=ZIP_DEFLATED) as package:
    package.writestr('SIRAJ_P0/docs/qa/CI_ACCEPTANCE.json', proof_json)
    package.writestr('SIRAJ_P0/docs/qa/CI_ACCEPTANCE_AR.md', md)
files = [output / 'SIRAJ_P0_UNIFIED_ANDROID_DEBUG.apk', archive]
lines = []
for file in files:
    with file.open('rb') as stream:
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    lines.append(f'{digest}  {file.name}\n')
    print(f'::notice title=SIRAJ artifact SHA256::{digest} {file.name}')
(output / 'SHA256SUMS').write_text(''.join(lines))
print('::notice title=SIRAJ verified acceptance::' + json.dumps({'host': host, 'native_passed': sum(r['passed'] for r in native), 'commit': commit}))
